    /** All known ISO-3166 alpha-2 country codes in the anchor table. */
    val codes: Set<String> get() = points.keys

    /** Number of country anchors. */
    val size: Int get() = points.size

    /** Returns the map anchor for [countryCode], or null when the code is unknown. */
    fun lookup(countryCode: String?): GeoPoint? {
        val normalized = countryCode
            ?.trim()
            ?.uppercase(java.util.Locale.ROOT)
            ?.takeIf { it.length == 2 && it.all { character -> character in 'A'..'Z' } }
            ?: return null
        return points[normalized]
    }
