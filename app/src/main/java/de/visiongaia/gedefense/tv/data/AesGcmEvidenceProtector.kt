package de.visiongaia.gedefense.tv.data

import de.visiongaia.gedefense.mobile.core.BoundedSecretKeyCrypto
import de.visiongaia.gedefense.mobile.core.EvidencePayloadProtector
import java.nio.charset.StandardCharsets
import java.security.GeneralSecurityException
import javax.crypto.Cipher
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * AES-256-GCM record protection for the local evidence ledger.
 *
 * The associated data binds every record to its ledger sequence number and timestamp, so a record
 * cannot be moved to another position or replayed under a different time without failing
 * authentication. The nonce is generated by the Keystore provider and prefixed (length byte + IV) to
 * the ciphertext, keeping unprotection independent of a provider-specific IV size.
 *
 * All provider calls run behind [BoundedSecretKeyCrypto] because an AndroidKeyStore AES key is
 * opaque and a vendor provider may block in native/Binder code.
 */
class AesGcmEvidenceProtector(private val key: SecretKey) : EvidencePayloadProtector {
    override fun protect(sequence: Long, atMillis: Long, plaintext: ByteArray): ByteArray {
        val binding = binding(sequence, atMillis)
        val (iv, payload) = BoundedSecretKeyCrypto.execute(key) {
            val cipher = Cipher.getInstance(TRANSFORMATION)
            cipher.init(Cipher.ENCRYPT_MODE, key)
            cipher.updateAAD(binding)
            val generatedIv = cipher.iv
                ?: throw GeneralSecurityException("AES-GCM provider returned no nonce")
            if (generatedIv.isEmpty() || generatedIv.size > MAX_IV_BYTES) {
                throw GeneralSecurityException("AES-GCM provider returned an invalid nonce")
            }
            generatedIv to cipher.doFinal(plaintext)
        }
        val output = ByteArray(1 + iv.size + payload.size)
        output[0] = iv.size.toByte()
        System.arraycopy(iv, 0, output, 1, iv.size)
        System.arraycopy(payload, 0, output, 1 + iv.size, payload.size)
        return output
    }

    override fun unprotect(sequence: Long, atMillis: Long, protectedPayload: ByteArray): ByteArray {
        if (protectedPayload.size < 1 + MIN_IV_BYTES + TAG_BYTES) {
            throw GeneralSecurityException("evidence payload too short")
        }
        val ivLength = protectedPayload[0].toInt() and 0xff
        if (ivLength !in MIN_IV_BYTES..MAX_IV_BYTES) {
            throw GeneralSecurityException("invalid evidence nonce length")
        }
        if (protectedPayload.size < 1 + ivLength + TAG_BYTES) {
            throw GeneralSecurityException("evidence payload too short")
        }
        val iv = protectedPayload.copyOfRange(1, 1 + ivLength)
        val payload = protectedPayload.copyOfRange(1 + ivLength, protectedPayload.size)
        val binding = binding(sequence, atMillis)
        return try {
            BoundedSecretKeyCrypto.execute(key) {
                val cipher = Cipher.getInstance(TRANSFORMATION)
                cipher.init(Cipher.DECRYPT_MODE, key, GCMParameterSpec(TAG_BYTES * 8, iv))
                cipher.updateAAD(binding)
                cipher.doFinal(payload)
            }
        } finally {
            iv.fill(0)
        }
    }

    private fun binding(sequence: Long, atMillis: Long): ByteArray =
        "$BINDING_PREFIX|$sequence|$atMillis".toByteArray(StandardCharsets.US_ASCII)

    companion object {
        private const val TRANSFORMATION = "AES/GCM/NoPadding"
        private const val BINDING_PREFIX = "vtevid1"
        private const val TAG_BYTES = 16
        private const val MIN_IV_BYTES = 12
        private const val MAX_IV_BYTES = 16
    }
}
